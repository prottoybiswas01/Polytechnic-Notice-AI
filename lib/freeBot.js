// lib/freeBot.js
import ADMIN_CONTACTS from "./admins";

export function getFreeResponse(messages) {
  const lastUserMessage = messages
    .filter((m) => m.role === "user")
    .pop()?.content || "";

  const text = lastUserMessage.toLowerCase();

  const adminList = ADMIN_CONTACTS.map(
    (a) => `- **${a.label}**: ${a.link}`
  ).join("\n");

  // 1. Eligibility
  if (
    text.includes("যোগ্যতা") ||
    text.includes("পয়েন্ট") ||
    text.includes("জিপিএ") ||
    text.includes("gpa") ||
    text.includes("ssc") ||
    text.includes("পয়েন্ট")
  ) {
    return `🎓 **পলিটেকনিক ভর্তির ন্যূনতম যোগ্যতা:**

**১. সরকারি পলিটেকনিক:**
- **ছেলেদের জন্য:** এসএসসি (SSC) বা সমমান পরীক্ষায় ন্যূনতম জিপিএ ৩.৫০ (গণিতে ন্যূনতম ৩.০০ পেতে হবে)।
- **মেয়েদের জন্য:** এসএসসি (SSC) বা সমমান পরীক্ষায় ন্যূনতম জিপিএ ৩.০০ (গণিতে ন্যূনতম ৩.০০ পেতে হবে)।

**২. বেসরকারি পলিটেকনিক:**
- সাধারণত এসএসসি (SSC) পাস করলেই আবেদন করা যায় (ন্যূনতম জিপিএ ২.০০)।

আপনার জিপিএ কত? আমাদের ফেসবুক গ্রুপে পোস্ট করলে অন্য অভিজ্ঞ ভাইদের থেকেও পরামর্শ পেতে পারেন।`;
  }

  // 2. Documents
  if (
    text.includes("কাগজ") ||
    text.includes("ডকুমেন্ট") ||
    text.includes("সার্টিফিকেট") ||
    text.includes("ছবি") ||
    text.includes("প্রয়োজনীয়") ||
    text.includes("কাগজপত্র") ||
    text.includes("paper")
  ) {
    return `📂 **ভর্তির জন্য প্রয়োজনীয় কাগজপত্র:**

১. এসএসসি (SSC) পরীক্ষার মূল মার্কশিট/একাডেমিক ট্রান্সক্রিপ্ট এবং ২/৩টি ফটোকপি।
২. এসএসসি পরীক্ষার মূল প্রশংসাপত্র (Testimonial)।
৩. সদ্য তোলা পাসপোর্ট সাইজের রঙিন ছবি (৩-৫ কপি)।
৪. এসএসসি পরীক্ষার প্রবেশপত্র (Admit Card) এবং রেজিস্ট্রেশন কার্ডের ফটোকপি।
৫. কোটা থাকলে (যেমন: মুক্তিযোদ্ধা, প্রতিবন্ধী, মহিলা কোটা ইত্যাদি) সংশ্লিষ্ট কোটার মূল সনদপত্র ও ফটোকপি।
৬. অনলাইন আবেদন ফর্ম এবং পেমেন্ট রিসিটের প্রিন্ট কপি।`;
  }

  // 3. Choice list
  if (
    text.includes("চয়েস") ||
    text.includes("লিস্ট") ||
    text.includes("choice") ||
    text.includes("list") ||
    text.includes("সাজাব") ||
    text.includes("সাজাবো")
  ) {
    return `📝 **চয়েস লিস্ট সাজানোর সেরা নিয়ম:**

১. **পছন্দসই টেকনোলজি আগে দিন:** আপনার যে বিষয়ে পড়ার আগ্রহ সবচেয়ে বেশি (যেমন: কম্পিউটার, সিভিল, ইলেকট্রিক্যাল, মেকানিক্যাল) সেটি তালিকার প্রথমে রাখুন।
২. **জিপিএ অনুযায়ী কলেজ নির্বাচন:** আপনার জিপিএ যদি একটু কম হয় (যেমন ৪.০০ এর নিচে), তবে ঢাকার বাইরের পলিটেকনিকগুলোকে চয়েস লিস্টে ওপরের দিকে রাখুন।
৩. **আসন সংখ্যা ও কোটা:** যে পলিটেকনিকে আসন সংখ্যা বেশি এবং যেখানে কম্পিটিশন কম হয়, সেখানে আবেদন করলে চান্স পাওয়ার সুযোগ বাড়ে।
৪. **একাধিক চয়েস দিন:** সরকারি পলিটেকনিকের ক্ষেত্রে সর্বোচ্চ চয়েস দেওয়ার চেষ্টা করুন যাতে কোনো না কোনোটিতে আপনার আসন নিশ্চিত হয়।`;
  }

  // 4. Benefits
  if (
    text.includes("সুবিধা") ||
    text.includes("চাকরি") ||
    text.includes("ভবিষ্যত") ||
    text.includes("ডুয়েট") ||
    text.includes("duet") ||
    text.includes("ভবিষ্যৎ") ||
    text.includes("ডিপ্লোমা কেন")
  ) {
    return `⚙️ **ডিপ্লোমা ইন ইঞ্জিনিয়ারিং পড়ার মূল সুবিধাসমূহ:**

১. **কর্মমুখী শিক্ষা:** থিওরির চেয়ে প্র্যাক্টিক্যাল কাজের ওপর বেশি জোর দেওয়া হয়, যা সরাসরি কাজের উপযোগী করে গড়ে তোলে।
২. **দ্রুত কর্মসংস্থান:** ৪ বছরের কোর্স শেষে সরাসরি সরকারি ও বেসরকারি চাকরিতে (১০ম গ্রেডে উপ-সহকারী প্রকৌশলী হিসেবে) যোগদানের বড় সুযোগ থাকে।
৩. **উচ্চশিক্ষা (DUET):** ডিপ্লোমা শেষ করে ঢাকা প্রকৌশল ও প্রযুক্তি বিশ্ববিদ্যালয় (DUET)-এ শুধুমাত্র ডিপ্লোমা হোল্ডারদের জন্য সংরক্ষিত কোটায় বিএসসি (B.Sc) করার সুযোগ রয়েছে।
৪. **সাশ্রয়ী পড়াশোনা:** সরকারি পলিটেকনিকে পড়ার খরচ সাধারণ অনার্স/ইঞ্জিনিয়ারিংয়ের চেয়ে অনেক কম।`;
  }

  // 5. Confirmation
  if (
    text.includes("নিশ্চায়ন") ||
    text.includes("নিশ্চয়ন") ||
    text.includes("নিশ্চিত") ||
    text.includes("টাকা") ||
    text.includes("ফি") ||
    text.includes("পেমেন্ট") ||
    text.includes("payment")
  ) {
    return `💳 **ভর্তি নিশ্চায়ন ও ফি সংক্রান্ত তথ্য:**

১. সরকারি পলিটেকনিকে প্রথম, দ্বিতীয় বা তৃতীয় মেরিট লিস্টে নাম আসার পর নির্দিষ্ট সময়ের মধ্যে **ভর্তি নিশ্চায়ন** করতে হয়।
২. নিশ্চায়ন ফি সাধারণত ২৩৮ টাকা বা বোর্ডের নির্ধারিত চার্জ হয়ে থাকে (বিকাশ, রকেট বা নগদের মাধ্যমে অনলাইনে দিতে হয়)।
৩. নির্ধারিত সময়ের মধ্যে নিশ্চায়ন না করলে আবেদনটি বাতিল হয়ে যাবে এবং পুনরায় আবেদন করতে হবে।

ভর্তি বিষয়ক অফিসিয়াল ওয়েবসাইট: [btebadmission.gov.bd](http://btebadmission.gov.bd)`;
  }

  // 6. Admins
  if (
    text.includes("এডমিন") ||
    text.includes("কন্টাক্ট") ||
    text.includes("যোগাযোগ") ||
    text.includes("হেল্প") ||
    text.includes("গ্রুপ") ||
    text.includes("হেল্পলাইন")
  ) {
    return `📞 **হেল্পলাইন ও এডমিনদের সাথে যোগাযোগের মাধ্যম:**

আপনার সমস্যা যদি জটিল বা ব্যক্তিগত হয়ে থাকে (যেমন: ভুল তথ্য সংশোধন বা কোটার সমস্যা), তবে সরাসরি আমাদের এডমিন প্যানেল বা গ্রুপে যোগাযোগ করুন:

${adminList}

আমরা দ্রুত উত্তর দেওয়ার চেষ্টা করব!`;
  }

  // 7. Greetings
  if (
    text.includes("সালাম") ||
    text.includes("আসসালামু") ||
    text.includes("hello") ||
    text.includes("hi") ||
    text.includes("হাই") ||
    text.includes("হ্যালো") ||
    text.includes("hello")
  ) {
    return `ওয়ালাইকুম আসসালাম! আমি পলিটেকনিক গাইড এআই 🎓। ডিপ্লোমা ভর্তি নিয়ে আমি আপনাকে কীভাবে সাহায্য করতে পারি? যেমন:
- ভর্তির যোগ্যতা (যেমন: কত পয়েন্ট লাগবে?)
- প্রয়োজনীয় কাগজপত্র (যেমন: কী কী পেপার লাগবে?)
- চয়েস লিস্ট সাজানোর নিয়ম
- ভর্তি নিশ্চায়ন ও ফি`;
  }

  // Default fallback
  return `আমি পলিটেকনিক ভর্তি সংক্রান্ত প্রশ্নের সমাধান দিতে পারি। আপনার প্রশ্নটি যদি নিচের কোনো বিষয়ের সাথে মিলে যায়, তবে দয়া করে আমাকে স্পষ্ট করে বলুন:

১. **ভর্তির যোগ্যতা** (যেমন: 'ভর্তি হতে কত পয়েন্ট লাগবে?')
২. **প্রয়োজনীয় কাগজপত্র** (যেমন: 'কী কী সার্টিফিকেট লাগবে?')
৩. **চয়েস লিস্ট সাজানো** (যেমন: 'চয়েস লিস্ট কীভাবে দেব?')
৪. **ডিপ্লোমার সুবিধা** (যেমন: 'ডিপ্লোমা করলে কী সুবিধা?')
৫. **ভর্তি নিশ্চায়ন** (যেমন: 'নিশ্চায়ন কীভাবে করতে হয়?')

অথবা যেকোনো জটিল সমস্যার জন্য আমাদের **ফেসবুক গ্রুপে** পোস্ট করতে পারেন বা **অ্যাডমিনের** সাহায্য নিতে পারেন:

${adminList}`;
}
